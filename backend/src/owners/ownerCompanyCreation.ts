/**
 * ownerCompanyCreation — internal seam used by venue registration.
 *
 * Creates (or reuses) the User's Owner, resolves the Company the venue joins,
 * and creates the Business in one transaction. The Owner is reachable from the
 * Business only through its Company.
 */

import { Types, type HydratedDocument } from "mongoose";
import { currenctyEnums } from "restaurant-pos-packages/enums";
import type { IBusiness } from "restaurant-pos-packages/interfaces/IBusiness";
import type { ICompany } from "restaurant-pos-packages/interfaces/ICompany";
import type { IOwner } from "restaurant-pos-packages/interfaces/IOwner";

import Business from "../models/business.ts";
import Company from "../models/company.ts";
import Owner from "../models/owner.ts";
import { runTxnWithTransientRetry } from "../mongo/runTxnWithTransientRetry.ts";

/** Domain refusals the HTTP layer maps to problem-details responses. */
export type OwnerCompanyCreationErrorCode =
  | "business-without-company"
  | "business-other-company"
  | "company-not-found"
  | "company-not-owned"
  | "company-duplicate"
  | "company-choice-required"
  | "country-required"
  | "currency-unsupported"
  | "owner-country-mismatch"
  | "company-country-mismatch";

export class OwnerCompanyCreationError extends Error {
  readonly code: OwnerCompanyCreationErrorCode;

  constructor(code: OwnerCompanyCreationErrorCode, message: string) {
    super(message);
    this.name = "OwnerCompanyCreationError";
    this.code = code;
  }
}

/**
 * The draft onboarding contract for a new venue. `_id` is generated by the
 * caller so a retried first-venue call resolves the same Business instead of
 * creating another one. Nothing outside these fields is writable here.
 */
export type BusinessCreationInput = {
  _id: Types.ObjectId | string;
  tradeName: string;
  currencyTrade: string;
  /** The venue country; it decides the portfolio country. */
  country: string;
};

export type OwnerCompanyCreationInput = {
  userId: Types.ObjectId | string;
  /** Draft onboarding fields only. */
  business: BusinessCreationInput;
  /** Join this existing Company when it belongs to the same Owner. */
  companyId?: Types.ObjectId | string;
  /** Fields for a newly formed Company; ignored when joining one. */
  company?: {
    legalName?: string;
    taxNumber?: string;
  };
};

export type OwnerCompanyCreationResult = {
  owner: HydratedDocument<IOwner>;
  company: HydratedDocument<ICompany>;
  business: HydratedDocument<IBusiness>;
};

function requiredCountry(country?: string): string {
  const trimmed = country?.trim() ?? "";
  if (!trimmed) {
    throw new OwnerCompanyCreationError(
      "country-required",
      "Business address country is required!",
    );
  }
  return trimmed;
}

function requiredSupportedCurrency(currency?: string): string {
  if (!currency || !currenctyEnums.includes(currency)) {
    throw new OwnerCompanyCreationError(
      "currency-unsupported",
      "Invalid currencyTrade!",
    );
  }
  return currency;
}

function optionalField(value?: string): string | undefined {
  const trimmed = value?.trim();
  return trimmed ? trimmed : undefined;
}

/**
 * Creates or reuses the User's Owner and the venue's Company, then creates the
 * Business linked to that Company. Calling again with the same Business `_id`
 * returns the existing Owner/Company pair instead of creating another.
 *
 * Rejects a venue whose country differs from the Owner's portfolio country, a
 * Company that is not owned by this User's Owner or sits in another country,
 * a Business id that already exists without an Owner Company, and a later
 * venue (an Owner that already has a Company) that supplies no Company choice.
 */
const ownerCompanyCreation = async (
  input: OwnerCompanyCreationInput,
): Promise<OwnerCompanyCreationResult> => {
  // Refuse an unsupported currency before the transaction can write anything,
  // so HTTP and direct callers obey the same currency rule.
  const currencyTrade = requiredSupportedCurrency(input.business.currencyTrade);

  const outcome = await runTxnWithTransientRetry(async (session) => {
    const existingBusiness = await Business.findById(input.business._id).session(
      session,
    );

    if (existingBusiness) {
      if (!existingBusiness.companyId) {
        throw new OwnerCompanyCreationError(
          "business-without-company",
          "Business already exists without an owning Company!",
        );
      }
      if (
        input.companyId &&
        String(input.companyId) !== String(existingBusiness.companyId)
      ) {
        throw new OwnerCompanyCreationError(
          "business-other-company",
          "Business already belongs to another Company!",
        );
      }

      const company = await Company.findById(existingBusiness.companyId).session(
        session,
      );
      if (!company) {
        throw new OwnerCompanyCreationError(
          "company-not-found",
          "Company not found for this Business!",
        );
      }

      const owner = await Owner.findOne({
        _id: company.ownerId,
        userId: input.userId,
      }).session(session);
      if (!owner) {
        throw new OwnerCompanyCreationError(
          "company-not-owned",
          "Company does not belong to this User's Owner!",
        );
      }

      return {
        type: "commit" as const,
        value: { owner, company, business: existingBusiness },
      };
    }

    const country = requiredCountry(input.business.country);

    let owner = await Owner.findOne({ userId: input.userId }).session(session);
    if (!owner) {
      const [createdOwner] = await Owner.create(
        [
          {
            userId: input.userId,
            country,
            subscription: "Free",
          },
        ],
        { session },
      );
      owner = createdOwner;
    } else if (owner.country !== country) {
      throw new OwnerCompanyCreationError(
        "owner-country-mismatch",
        "Venue country must match the Owner's portfolio country!",
      );
    } else if (!input.companyId && input.company === undefined) {
      const companyCount = await Company.countDocuments({
        ownerId: owner._id,
      }).session(session);
      if (companyCount > 0) {
        throw new OwnerCompanyCreationError(
          "company-choice-required",
          "A Company choice is required for an additional venue!",
        );
      }
    }

    let company: HydratedDocument<ICompany>;
    if (input.companyId) {
      const joinedCompany = await Company.findOne({
        _id: input.companyId,
        ownerId: owner._id,
      }).session(session);
      if (!joinedCompany) {
        throw new OwnerCompanyCreationError(
          "company-not-owned",
          "Company does not belong to this User's Owner!",
        );
      }
      if (joinedCompany.country !== country) {
        throw new OwnerCompanyCreationError(
          "company-country-mismatch",
          "Company country must match the Owner's portfolio country!",
        );
      }
      company = joinedCompany;
    } else {
      try {
        const [createdCompany] = await Company.create(
          [
            {
              ownerId: owner._id,
              country,
              legalName: optionalField(input.company?.legalName),
              taxNumber: optionalField(input.company?.taxNumber),
            },
          ],
          { session },
        );
        company = createdCompany;
      } catch (error) {
        if ((error as { code?: unknown } | null)?.code === 11000) {
          throw new OwnerCompanyCreationError(
            "company-duplicate",
            "Company legal name or tax number already exists!",
          );
        }
        throw error;
      }
    }

    // Construct the draft from an explicit allowlist so a direct caller cannot
    // write legacy legal/tax identity, timezone, ratings, or credentials.
    const [business] = await Business.create(
      [
        {
          _id: input.business._id,
          tradeName: input.business.tradeName,
          currencyTrade,
          address: { country },
          companyId: company._id,
        },
      ],
      { session },
    );

    return {
      type: "commit" as const,
      value: { owner, company, business },
    };
  });

  return outcome.value;
};

export default ownerCompanyCreation;
